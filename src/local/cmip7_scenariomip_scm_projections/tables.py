"""
Tables for the manuscript

Each table is written as the body of a `tabular` environment
(caption, label etc. are in the manuscript's latex)
and is inlined in place of its tag when the manuscript is assembled.
"""

from __future__ import annotations

from pathlib import Path

from local.cmip7_scenariomip_scm_projections.scenarios import SCENARIOS
from local.cmip7_scenariomip_scm_projections.warming import PEAK
from local.feather_io import load_feather_df

GENERATED_COMMENT = "% Generated by {source}, do not edit by hand"


def write_table(out_file: Path, lines: list[str], source: str) -> Path:
    """Write a table's lines"""
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(
        "\n".join([GENERATED_COMMENT.format(source=source), *lines]) + "\n"
    )

    return out_file


def generate_peak_warming_table(out_file: Path, metrics_quantiles_file: Path) -> Path:
    """
    Generate the table of peak warming (median and 5th to 95th percentile)

    Parameters
    ----------
    out_file
        File in which to write the table

    metrics_quantiles_file
        File which holds the quantiles of the warming metrics

    Returns
    -------
    :
        `out_file`
    """
    metrics_quantiles = load_feather_df(metrics_quantiles_file)
    peak = metrics_quantiles.loc[
        metrics_quantiles.index.get_level_values("metric") == PEAK
    ]

    lines = [
        r"\begin{tabular}{llccc}",
        r"\toprule",
        r"Scenario & Model & Median (K) & 5th percentile (K) & 95th percentile (K) \\",
        r"\midrule",
    ]
    for scenario in SCENARIOS:
        q = peak.loc[
            (peak.index.get_level_values("model") == scenario.model)
            & (peak.index.get_level_values("scenario") == scenario.scenario)
        ].squeeze()
        lines.append(
            f"{scenario.label} & {scenario.model} & "
            f"{q[0.5]:.2f} & {q[0.05]:.2f} & {q[0.95]:.2f} \\\\"
        )

    lines.extend([r"\bottomrule", r"\end{tabular}"])

    return write_table(out_file, lines, source=__name__)
